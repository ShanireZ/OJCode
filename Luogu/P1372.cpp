#include <iostream>
#include <cmath>
using namespace std;
int main()
{
    //題目位從1~n中選取k個數，並使得挑選的k個數的最大公約數最大
    //兩個數如果不是倍數關係，那麼他們的最大公約數位1
    //兩個數如果是倍數關係，那麼他們的最大公約數為較小的數
    //那麼k個數如果要使得他們的最大公約數儘可能大，那麼他們需要是倍數關係
    //也就是說這k個數為x 2x 3x 4x 5x ..... kx
    //中間不能跳過，如果跳過，那麼必然會有比跳過時更大的公約數
    //我們為了使公約數儘可能大，那麼kx要儘可能的接近n
    //最大的情況就是kx=n，此時x = n / k
    int n, k;
    cin >> n >> k;
    cout << n / k;
    return 0;
}